#!/usr/bin/env python3
"""Generate the health-strip tables from docs/health-strip-table.tsv.

The TSV is the single source of truth (decided field by field from the FIT SDK
profile, third_party/fit-sdk/cpp/fit_profile.hpp). This script writes:

  src/health_table.inc    C++ allow-lists used by src/health_stripper.cpp
  docs/health-strip.md    the human readable table

Run from the repository root:  python3 tools/gen_health_table.py
tests/run_tests.sh runs it with --check and fails when the generated files are
not up to date.
"""
import collections
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TSV = os.path.join(ROOT, "docs", "health-strip-table.tsv")
INC = os.path.join(ROOT, "src", "health_table.inc")
DOC = os.path.join(ROOT, "docs", "health-strip.md")


def load():
    msgs = collections.OrderedDict()  # num -> dict(name, decision, reason, fields[])
    events = []
    for line in open(TSV, encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        kind, mnum, mname, fnum, fname, units, dec, reason, hr = line.rstrip("\n").split("\t")
        mnum = int(mnum)
        if dec not in ("K", "R") or hr not in ("K", "R"):
            raise SystemExit("bad decision in row: " + line)
        # --strip-hr removes a subset of what --strip-health removes
        if dec == "K" and hr != "K":
            raise SystemExit("row kept by --strip-health but removed by --strip-hr: " + line)
        if kind == "M":
            # whole messages: the same decision in both modes
            if hr != dec:
                raise SystemExit("message rows need the same decision in both modes: " + line)
            msgs[mnum] = {"name": mname, "dec": dec, "reason": reason, "fields": []}
        elif kind == "F":
            msgs[mnum]["fields"].append((int(fnum), fname, units, dec, reason, hr))
        elif kind == "E":
            events.append((int(fnum), fname, dec, reason, hr))
        else:
            raise SystemExit("bad row kind " + kind)
    return msgs, events


def gen_inc(msgs, events):
    o = []
    o.append("// GENERATED by tools/gen_health_table.py from docs/health-strip-table.tsv. Do not edit.")
    o.append("// Allow-lists: a message or field that is not listed here is removed.")
    o.append("// kKeep* = --strip-health, kHrKeep* = --strip-hr (heart rate and health only; power and cadence stay).")
    o.append("")
    for prefix, col in (("kKeep", 3), ("kHrKeep", 5)):
        for num, m in msgs.items():
            if m["dec"] != "K":
                continue
            kept = [str(f[0]) for f in m["fields"] if f[col] == "K"]
            o.append("static const uint8_t %s_%d[] = {%s}; // %s" % (prefix, num, ", ".join(kept), m["name"]))
        o.append("")
    for name, prefix in (("kKeepRules", "kKeep"), ("kHrKeepRules", "kHrKeep")):
        o.append("static const HealthKeepRule %s[] = {" % name)
        for num, m in msgs.items():
            if m["dec"] != "K":
                continue
            o.append("    {%d, %s_%d, sizeof(%s_%d)}, // %s" % (num, prefix, num, prefix, num, m["name"]))
        o.append("};")
        o.append("")
    o.append("// event.event values that may stay (all others, and values unknown to the profile, drop the message)")
    o.append("static const uint8_t kKeepEvents[] = {%s};" % ", ".join(str(e[0]) for e in events if e[2] == "K"))
    o.append("static const uint8_t kHrKeepEvents[] = {%s};" % ", ".join(str(e[0]) for e in events if e[4] == "K"))
    o.append("")
    return "\n".join(o)


def gen_doc(msgs, events):
    kept = [(n, m) for n, m in msgs.items() if m["dec"] == "K"]
    dropped = [(n, m) for n, m in msgs.items() if m["dec"] != "K"]
    o = []
    o.append("# Health strip table (fit-parser `--strip-health` and `--strip-hr`)")
    o.append("")
    o.append("GENERATED by `tools/gen_health_table.py` from `docs/health-strip-table.tsv`. Edit the TSV, not this file.")
    o.append("")
    o.append("Source: Garmin FIT SDK profile 21.158 (`third_party/fit-sdk/cpp/fit_profile.hpp`), every message and every field of it.")
    o.append("")
    o.append("Two modes use this one table:")
    o.append("")
    o.append("- `--strip-health`: removes every physiological and biomechanical value (heart rate, power, cadence, ...). Column \"health\".")
    o.append("- `--strip-hr` (v2.5.0): removes heart rate and other body data, but keeps power, cadence, pedalling dynamics, work,")
    o.append("  e-bike motor power, standing time and trainer resistance (for bike part wear). Column \"hr\".")
    o.append("  It removes a subset of what `--strip-health` removes; whole messages, developer data and the rules below are the same in both modes.")
    o.append("")
    o.append("## Rules")
    o.append("")
    o.append("1. **Allow-list.** Only the messages in the first table survive, and in them only the fields marked KEEP.")
    o.append("   Everything else is removed: all other global messages, fields the profile does not know, and messages the profile does not know.")
    o.append("   A field added to the profile in a later SDK is therefore removed until someone decides to keep it.")
    o.append("2. **All developer data goes**: `developer_data_id`, `field_description` and the developer fields on every message")
    o.append("   (CORE body temperature, Stryd power, Moxy and friends carry their values there; their meaning cannot be trusted).")
    o.append("3. **Event messages** pass only for the event types marked KEEP in the event table. Their `data` field means a")
    o.append("   heart rate / power / cadence threshold for the alert events, so those events are dropped whole, and an event")
    o.append("   without an `event` value or with a value the profile does not know is dropped too.")
    o.append("4. Kept: time, position, altitude, distance, speed, ambient temperature, grade, GPS accuracy, events, laps and sessions")
    o.append("   (times, distances, ascent, speed, sport), device and file info (including sensor battery).")
    o.append("5. Components: the output is re-encoded from the original fields only (expanded component fields are discarded first).")
    o.append("   Kept fields whose components feed another field only feed kept fields (checked: `record.altitude` -> `enhanced_altitude`,")
    o.append("   `record.speed` -> `enhanced_speed`, `record.compressed_speed_distance` -> `speed`, `distance`; lap and session speed / altitude likewise).")
    o.append("   The one exception is `event.data` -> `score` / `opponent_score` (sport_point subfield); those fields are removed and the event is dropped.")
    o.append("")
    o.append("## Kept messages and their fields")
    o.append("")
    for n, m in kept:
        o.append("### %d `%s` - %s" % (n, m["name"], m["reason"]))
        o.append("")
        o.append("| field | name | units | health | hr | reason |")
        o.append("|---:|---|---|---|---|---|")
        for fnum, fname, units, dec, reason, hr in m["fields"]:
            o.append("| %d | `%s` | %s | %s | %s | %s |" % (fnum, fname, units or "", "KEEP" if dec == "K" else "**REMOVE**",
                                                       "KEEP" if hr == "K" else "**REMOVE**", reason))
        o.append("")
    o.append("## `event.event` values")
    o.append("")
    o.append("| value | name | health | hr | reason |")
    o.append("|---:|---|---|---|---|")
    for v, name, dec, reason, hr in events:
        o.append("| %d | `%s` | %s | %s | %s |" % (v, name, "KEEP" if dec == "K" else "**DROP**", "KEEP" if hr == "K" else "**DROP**", reason))
    o.append("")
    o.append("## Dropped messages (every field in them goes, in both modes)")
    o.append("")
    o.append("| message | name | reason |")
    o.append("|---:|---|---|")
    for n, m in dropped:
        o.append("| %d | `%s` | %s |" % (n, m["name"], m["reason"]))
    o.append("")
    return "\n".join(o)


def main():
    msgs, events = load()
    outputs = {INC: gen_inc(msgs, events), DOC: gen_doc(msgs, events)}
    if "--check" in sys.argv:
        bad = False
        for path, text in outputs.items():
            if not os.path.exists(path) or open(path, encoding="utf-8").read() != text:
                print("out of date: " + os.path.relpath(path, ROOT))
                bad = True
        sys.exit(1 if bad else 0)
    for path, text in outputs.items():
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        print("wrote " + os.path.relpath(path, ROOT))


if __name__ == "__main__":
    main()
